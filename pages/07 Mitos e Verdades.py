import streamlit as st

# Título da Seção (Mesmo tom azul vibrante do Checklist e CID)
st.markdown("<h2 style='color: #00416d; font-weight: bold;'>🚫 Mitos vs. Verdades sobre a Fibromialgia</h2>", unsafe_allow_html=True)

# --- MITO 1 ---
st.markdown("### :blue[1. 'A fibromialgia é coisa da sua cabeça.']")
st.markdown("❌ **MITO.**")
st.markdown("✔️ **Verdade:** Embora o estresse possa piorar os sintomas, a fibromialgia é uma condição neurofisiológica. Exames de imagem mostram que o cérebro processa a dor de forma diferente. A dor é real e física.")

# --- MITO 2 ---
st.markdown("### :blue[2. 'Se os exames de sangue deram normais, você não tem nada.']")
st.markdown("❌ **MITO.**")
st.markdown("✔️ **Verdade:** Não existe marcador no sangue para a fibromialgia. O diagnóstico é clínico, baseado nos sintomas e no histórico do paciente realizado por um especialista.")

# --- MITO 3 ---
st.markdown("### :blue[3. 'Quem tem fibromialgia não deve fazer exercícios.']")
st.markdown("❌ **MITO.**")
st.markdown("✔️ **Verdade:** O repouso absoluto é um inimigo. Exercícios de baixo impacto (caminhada, hidroginástica) ajudam o cérebro a liberar substâncias que aliviam a dor naturalmente.")

# --- MITO 4 ---
st.markdown("### :blue[4. 'A fibromialgia é uma doença autoimune.']")
st.markdown("❌ **MITO.**")
st.markdown("✔️ **Verdade:** Ao contrário do Lúpus, o sistema imunológico não ataca os tecidos. Ela é uma síndrome de sensibilização central.")

# --- MITO 5 ---
st.markdown("### :blue[5. 'É uma doença que só afeta mulheres.']")
st.markdown("❌ **MITO.**")
st.markdown("✔️ **Verdade:** Embora mais comum em mulheres, também afeta homens, idosos e crianças. Em homens, o diagnóstico costuma demorar mais devido ao estigma.")

# --- MITO 6 ---
st.markdown("### :blue[6. 'Fibromialgia tem cura.']")
st.markdown("❌ **MITO.**")
st.markdown("✔️ **Verdade:** É uma condição crônica, mas é possível alcançar a remissão (viver sem dor) através de tratamento multidisciplinar.")

# --- MITO 7 ---
st.markdown("### :blue[7. 'A dor é igual todos os dias.']")
st.markdown("❌ **MITO.**")
st.markdown("✔️ **Verdade:** A condição oscila. Existem dias de crise e dias de estabilidade, influenciados por sono, estresse ou temperatura.")